/** Recria o banco de teste do zero, com a estrutura e os dados acima. */
export async function createSankhyaBase(): Promise<void> {
  await sqlcmd(`
IF DB_ID('${DATABASE}') IS NOT NULL
BEGIN
  ALTER DATABASE ${DATABASE} SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
  DROP DATABASE ${DATABASE};
END;
CREATE DATABASE ${DATABASE} COLLATE Latin1_General_CI_AI;`);
  await sqlcmd(`SET NOCOUNT ON;\n${SCHEMA}\n${seed()}`, DATABASE);
}
